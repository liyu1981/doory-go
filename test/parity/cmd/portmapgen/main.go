// Command portmapgen generates docs/parity/PORT_MAP.md: one row for every
// tracked upstream backend file (see parity.TrackedBackendFiles). Sections
// and the upstream column are generated; hand-maintained `go` and `status`
// cells are preserved across regeneration.
//
// Row granularity: one row per source file, except tests/, migrations/ and
// management/ trees, which collapse to a single directory-prefix row.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"doory-go/internal/parity"
)

// headerTemplate avoids backtick characters (raw-string limitation); paths in
// the prose are shown indented or quoted with ' instead of markdown code spans.
func headerTemplate() string {
	return strings.Join([]string{
		"# PORT_MAP",
		"",
		"Where the Go port of the pinned doory backend lives. **Status here means code",
		"mapping only, not parity proof.** Verification quality is tracked separately",
		"in test/parity/coverage.md (boot-only/smoke scenarios never count as",
		"behavioral verification).",
		"",
		"- Upstream paths are mirror-root-relative (backend/...), one row per tracked",
		"  source file, except tests/, migrations/ and management/ trees which use a",
		"  directory-prefix row (trailing '/').",
		"- Tracked denominator: every *.py except __init__.py (Go has no barrels; those",
		"  are noted once as n/a), every *.html template, every backend/data/*.json",
		"  seed fixture.",
		"- Status vocabulary: 'OK' is not used; statuses are: ported (done symbol),",
		"  partial (half symbol), not-started (white square), deferred (pause),",
		"  broken (red), n/a. See the rows below for the exact symbols.",
		"- The upstream column and sections are GENERATED by pnpm generate",
		"  (test/parity/cmd/portmapgen); the go/status cells are review state and are",
		"  preserved across regeneration. Never hand-edit generated cells.",
		"- Every production Go port file carries a '// Ports backend/...' comment;",
		"  pnpm port-map-drift rejects such claims without a reviewed row, rows whose",
		"  upstream file vanished, and tracked files with no row.",
		"- The upstream pin lives only in internal/dooryversion/dooryversion.go; this",
		"  map intentionally does not copy it.",
		"",
	}, "\n")
}

func main() {
	root, err := parity.RepoRoot()
	if err != nil {
		fatal(err)
	}
	tracked, err := parity.TrackedBackendFiles(filepath.Join(root, ".upstream", "current"))
	if err != nil {
		fatal(err)
	}

	// Preserve hand-maintained cells from the existing map.
	old := map[string]parity.PortMapRow{}
	if existing, err := parity.ParsePortMap(filepath.Join(root, "docs", "parity", "PORT_MAP.md")); err == nil {
		for _, r := range existing {
			old[r.Upstream] = r
		}
	}

	rowset := map[string]bool{}
	for _, f := range tracked {
		rowset[deriveRow(f)] = true
	}
	var rows []string
	for r := range rowset {
		rows = append(rows, r)
	}
	sort.Strings(rows)

	// Group rows into sections by parent directory.
	sections := map[string][]string{}
	for _, r := range rows {
		parent := filepath.ToSlash(filepath.Dir(strings.TrimSuffix(r, "/")))
		sections[parent] = append(sections[parent], r)
	}
	var sectionNames []string
	for s := range sections {
		sectionNames = append(sectionNames, s)
	}
	sort.Strings(sectionNames)

	var b strings.Builder
	b.WriteString(headerTemplate())
	for _, section := range sectionNames {
		fmt.Fprintf(&b, "## `%s/`\n\n", section)
		b.WriteString("| upstream | go | status |\n|---|---|---|\n")
		for _, r := range sections[section] {
			goCell, status := "", "⬜"
			if prev, ok := old[r]; ok {
				goCell, status = prev.Go, prev.Status
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", r, goCell, status)
		}
		b.WriteString("\n")
	}

	out := filepath.Join(root, "docs", "parity", "PORT_MAP.md")
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("portmapgen: %d tracked files -> %d rows in %d sections -> %s\n",
		len(tracked), len(rows), len(sectionNames), out)
}

// deriveRow maps a tracked file to its row path: tests/, migrations/ and
// management/ trees collapse to a directory-prefix row.
func deriveRow(file string) string {
	for _, dir := range []string{"migrations", "tests", "management"} {
		if idx := strings.Index(file, "/"+dir+"/"); idx >= 0 {
			return file[:idx] + "/" + dir + "/"
		}
	}
	return file
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "portmapgen:", err)
	os.Exit(1)
}
