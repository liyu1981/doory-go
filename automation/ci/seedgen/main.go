// Command seedgen dumps seed-table rows from the migrated oracle database
// into an embeddable SQL file (doory/migrations/*.seed.sqlite.sql).
//
// Content parity without porting importers: the rows the Django migration
// produced (from backend/data/*.json) are copied verbatim — including JSON
// column text, which responses pass through byte-for-byte. Whitelisted
// tables only, deterministic ORDER BY pk, SQL-escaped literals.
//
// Postgres seed dump lands with the http dialect lane (rows are not part of
// the schema digest; the size-presets scenario is sqlite-declared until
// then).
package main

import (
	"database/sql"
	"flag"
	"fmt"
	"os"
	"strings"

	_ "modernc.org/sqlite"
)

func main() {
	dbPath := flag.String("db", ".oracle/oracle.sqlite3", "oracle sqlite database")
	out := flag.String("out", "", "output seed file")
	tables := flag.String("tables", "", "comma-separated tables (pk ordered)")
	flag.Parse()
	if *out == "" || *tables == "" {
		fmt.Fprintln(os.Stderr, "usage: seedgen -out file -tables a,b [-db path]")
		os.Exit(2)
	}
	db, err := sql.Open("sqlite", *dbPath)
	if err != nil {
		fatal(err)
	}
	defer db.Close()

	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by pnpm seedgen from the migrated oracle (%s).\n", *dbPath)
	b.WriteString("-- Seed rows verbatim (JSON columns keep their stored text — responses pass\n")
	b.WriteString("-- them through byte-for-byte). Never hand-edit; regenerate + parity-prove.\n\n")

	total := 0
	for _, table := range strings.Split(*tables, ",") {
		table = strings.TrimSpace(table)
		cols, err := columnNames(db, table)
		if err != nil {
			fatal(fmt.Errorf("%s: %w", table, err))
		}
		rows, err := db.Query(fmt.Sprintf("SELECT %s FROM %s ORDER BY rowid", strings.Join(quoteAll(cols), ","), table))
		if err != nil {
			fatal(fmt.Errorf("%s: %w", table, err))
		}
		for rows.Next() {
			vals := make([]any, len(cols))
			ptrs := make([]any, len(cols))
			for i := range vals {
				ptrs[i] = &vals[i]
			}
			if err := rows.Scan(ptrs...); err != nil {
				rows.Close()
				fatal(err)
			}
			lits := make([]string, len(cols))
			for i, v := range vals {
				lits[i] = literal(v)
			}
			fmt.Fprintf(&b, "INSERT INTO %q (%s) VALUES (%s);\n",
				table, strings.Join(quoteAll(cols), ", "), strings.Join(lits, ", "))
			total++
		}
		rows.Close()
		if rows.Err() != nil {
			fatal(rows.Err())
		}
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("seedgen: %d rows -> %s\n", total, *out)
}

func columnNames(db *sql.DB, table string) ([]string, error) {
	rows, err := db.Query(fmt.Sprintf("SELECT * FROM %q LIMIT 0", table))
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	return rows.Columns()
}

func quoteAll(in []string) []string {
	out := make([]string, len(in))
	for i, s := range in {
		out[i] = fmt.Sprintf("%q", s)
	}
	return out
}

func literal(v any) string {
	switch x := v.(type) {
	case nil:
		return "NULL"
	case int64:
		return fmt.Sprintf("%d", x)
	case float64:
		return fmt.Sprintf("%v", x)
	case []byte:
		return fmt.Sprintf("%q", string(x)) // sqlite strings
	case string:
		return "'" + strings.ReplaceAll(x, "'", "''") + "'"
	default:
		return "'" + strings.ReplaceAll(fmt.Sprint(x), "'", "''") + "'"
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "seedgen:", err)
	os.Exit(1)
}
